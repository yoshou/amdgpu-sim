//! DS: the LDS instructions.
//!
//! The harness seeds LDS before the instruction runs, so a load can be checked
//! by the value it returns rather than by the address it used -- the simulator
//! and the hardware never put LDS in the same place. A store is checked the
//! same way round: the case states what the lane's words became.
//!
//! Every case states both what the destination registers hold and what the
//! lane's eight LDS words hold, so an instruction that writes the wrong
//! register or the wrong address fails rather than passing on the one word the
//! test happened to look at. Two lanes are checked, so an implementation that
//! uses one lane's address for the whole wave cannot pass either.

use crate::encoding::*;
use crate::harness::*;
use amdgpu_sim::rdna_processor::Engine;

/// The lanes every case checks.
const CHECK_LANES: [usize; 2] = [0, 7];

/// The values the harness puts in v2..v5, which a store writes to LDS.
const STORE_VALUES: [u32; 4] = [0x1234_5678, 0x9ABC_DEF0, 0x0F0F_0F0F, 0xF0F0_F0F0];

/// One DS case. Both offset fields are stated, since a single-address
/// instruction reads them as one 16-bit byte offset while a two-address one
/// reads them as two element indices.
pub(crate) struct DsCase {
    pub(crate) offset0: u8,
    pub(crate) offset1: u8,
    /// v[6:9] of each checked lane after the instruction.
    pub(crate) vdst: [[u32; 4]; CHECK_LANES.len()],
    /// The eight LDS words each checked lane owns, after the instruction.
    pub(crate) lds: [[u32; 8]; CHECK_LANES.len()],
}

/// Runs one case on one engine and returns (v[6:9], LDS words) per checked lane.
fn run(harness: &Harness, engine: Engine, words: &[u32]) -> ([[u32; 4]; 2], [[u32; 8]; 2]) {
    let mut src = vec![0u32; LANES * harness.src_stride];
    for lane in 0..LANES {
        for (k, value) in STORE_VALUES.iter().enumerate() {
            src[lane * harness.src_stride + k] = value ^ (lane as u32 * 0x0101_0101);
        }
    }
    let uni = vec![0u32; 8];
    let out = harness.run(engine, words, &src, &uni);

    let mut vdst = [[0u32; 4]; 2];
    let mut lds = [[0u32; 8]; 2];
    for (slot, lane) in CHECK_LANES.iter().enumerate() {
        let base = lane * harness.out_stride;
        vdst[slot].copy_from_slice(&out[base..base + 4]);
        lds[slot].copy_from_slice(&out[base + 4..base + 12]);
    }
    (vdst, lds)
}

fn report(failures: Vec<String>, total: usize) {
    assert!(
        failures.is_empty(),
        "{} of {} case-results differ from hardware:\n{}",
        failures.len(),
        total,
        failures.join("\n"),
    );
}

fn describe(vdst: &[[u32; 4]; 2], lds: &[[u32; 8]; 2]) -> String {
    let mut text = String::new();
    for (slot, lane) in CHECK_LANES.iter().enumerate() {
        text.push_str(&format!(
            " lane {}: vdst [{}] lds [{}]",
            lane,
            vdst[slot]
                .iter()
                .map(|v| format!("{:08X}", v))
                .collect::<Vec<_>>()
                .join(" "),
            lds[slot]
                .iter()
                .map(|v| format!("{:08X}", v))
                .collect::<Vec<_>>()
                .join(" "),
        ));
    }
    text
}

/// A DS load: it writes VDST and leaves LDS alone. Compared bit-exactly; there
/// is nothing approximate about moving bits out of memory.
pub(crate) fn check_ds_load(op: u32, cases: &[DsCase]) {
    let harness = Harness::lds();
    let mut failures = Vec::new();
    for (i, case) in cases.iter().enumerate() {
        let words = ds(op, 6, 0, 2, 3, case.offset0 as u32, case.offset1 as u32).to_vec();
        for engine in [Engine::Interpreter, Engine::LlvmJit] {
            let (vdst, lds) = run(&harness, engine, &words);
            if vdst == case.vdst && lds == case.lds {
                continue;
            }
            failures.push(format!(
                "  {:<11} case {} (offset0={} offset1={})\n    hardware  {}\n    simulator {}",
                engine_name(engine),
                i,
                case.offset0,
                case.offset1,
                describe(&case.vdst, &case.lds),
                describe(&vdst, &lds),
            ));
        }
    }
    report(failures, cases.len() * 2);
}

/// A DS store: it writes LDS and leaves VDST alone. The data registers are
/// v[2:5], which the harness fills with a per-lane pattern.
pub(crate) fn check_ds_store(op: u32, cases: &[DsCase]) {
    let harness = Harness::lds();
    let mut failures = Vec::new();
    for (i, case) in cases.iter().enumerate() {
        let words = ds(op, 6, 0, 2, 3, case.offset0 as u32, case.offset1 as u32).to_vec();
        for engine in [Engine::Interpreter, Engine::LlvmJit] {
            let (vdst, lds) = run(&harness, engine, &words);
            if vdst == case.vdst && lds == case.lds {
                continue;
            }
            failures.push(format!(
                "  {:<11} case {} (offset0={} offset1={})\n    hardware  {}\n    simulator {}",
                engine_name(engine),
                i,
                case.offset0,
                case.offset1,
                describe(&case.vdst, &case.lds),
                describe(&vdst, &lds),
            ));
        }
    }
    report(failures, cases.len() * 2);
}

